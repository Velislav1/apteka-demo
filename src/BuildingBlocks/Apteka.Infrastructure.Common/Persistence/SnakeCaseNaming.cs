using System.Text;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;

namespace Apteka.Infrastructure.Common.Persistence;

/// <summary>PostgreSQL naming: tables, columns, keys and indexes in snake_case (ProductUnitId → product_unit_id).</summary>
public static class SnakeCaseNaming
{
    public static void Apply(ModelBuilder modelBuilder)
    {
        foreach (var entity in modelBuilder.Model.GetEntityTypes())
        {
            if (entity.GetTableName() is { } table && !entity.IsOwned())
